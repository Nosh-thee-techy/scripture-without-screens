def normalize_lang(language: str | None) -> str:
    """Map a session language code onto a supported i18n table."""

    code = (language or "en").strip().lower()
    aliases = {
        "swh": "sw",
        "swa": "sw",
        "eng": "en",
        "kik": "ki",
        "kal": "kln",
        "orm": "gax",
        "borana": "gax",
    }
    code = aliases.get(code, code)
    return code if code in STRINGS else "en"


def t(language: str | None, key: str, **kwargs: object) -> str:
    """Translate one UI string, falling back to English if needed."""

    lang = normalize_lang(language)
    template = STRINGS.get(lang, {}).get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def nav_footer(language: str | None) -> str:
    """Localized Change Language / Home footer used on nested screens."""

    return t(language, "nav_footer")


def main_menu(language: str | None) -> str:
    """Build the localized main USSD menu."""

    lang = normalize_lang(language)
    return "\n".join(
        [
            t(lang, "main_title"),
            f"1. {t(lang, 'menu_votd')}",
            f"2. {t(lang, 'menu_read_bible')}",
            f"3. {t(lang, 'menu_reading_plan')}",
            f"4. {t(lang, 'menu_kids')}",
            f"5. {t(lang, 'menu_bible_version')}",
            f"6. {t(lang, 'menu_language')}",
            f"0. {t(lang, 'home')}",
        ]
    )


def category_name(language: str | None, category_id: str) -> str:
    """Localized reading-plan topic label."""

    key = f"plan_cat_{category_id}"
    return t(language, key)
